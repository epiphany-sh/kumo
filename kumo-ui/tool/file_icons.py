#!/usr/bin/env python3
"""Vendors Material Icon Theme's file and folder icons.

Downloads the `material-icon-theme` npm package (MIT), copies every icon to
assets/file_icons/<name>.svg and writes lib/widgets/file_icons.g.dart: which
icon a file name, an extension or a folder name gets.

    python3 tool/file_icons.py 5.40.0
"""

import io
import json
import re
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

UI = Path(__file__).resolve().parent.parent
ASSETS = UI / "assets" / "file_icons"
DART = UI / "lib" / "widgets" / "file_icons.g.dart"
PACKAGE = "material-icon-theme"


def download(version):
    url = f"https://registry.npmjs.org/{PACKAGE}/-/{PACKAGE}-{version}.tgz"
    # curl, not urllib: python.org builds on macOS ship without CA certificates.
    data = subprocess.run(["curl", "-fsSL", url], check=True, capture_output=True).stdout
    files = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for member in tar.getmembers():
            if member.isfile():
                files[member.name.removeprefix("package/")] = tar.extractfile(member).read()
    return files


def folder_base(name):
    """`src`, `.src`, `_src`, `-src` and `__src__` all share one entry."""
    m = re.fullmatch(r"__(.+)__", name)
    if m:
        return m.group(1)
    return name[1:] if name[:1] in "._-" and len(name) > 1 else name


def dart_map(name, entries, doc):
    lines = [f"/// {doc}", f"const {name} = <String, String>{{"]
    lines += [f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v)}," for k, v in sorted(entries.items())]
    lines.append("};")
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    version = sys.argv[1]
    files = download(version)
    theme = json.loads(files["dist/material-icons.json"])

    # Every definition, under its own name (a few files are `*.clone.svg`).
    shutil.rmtree(ASSETS, ignore_errors=True)
    ASSETS.mkdir(parents=True)
    defs = theme["iconDefinitions"]
    for name, definition in defs.items():
        path = definition["iconPath"].removeprefix("./../")
        (ASSETS / f"{name}.svg").write_bytes(files[path])
    (ASSETS / "LICENSE.txt").write_bytes(files["LICENSE"])

    file_names = {k.lower(): v for k, v in theme["fileNames"].items()}
    extensions = {k.lower(): v for k, v in theme["fileExtensions"].items()}
    folders = {}
    for name, icon in theme["folderNames"].items():
        base = folder_base(name.lower())
        assert folders.get(base, icon) == icon, f"{name}: {folders[base]} vs {icon}"
        assert theme["folderNamesExpanded"][name] == f"{icon}-open", name
        folders[base] = icon
    # Every name the table hands out has its SVG.
    referenced = {*file_names.values(), *extensions.values(), *folders.values(), "file", "folder"}
    referenced |= {f"{icon}-open" for icon in [*folders.values(), "folder"]}
    assert referenced <= defs.keys(), sorted(referenced - defs.keys())
    light = sorted(n.removesuffix("_light") for n in defs if n.endswith("_light"))

    DART.write_text(
        "\n\n".join(
            [
                f"// Generated by tool/file_icons.py from {PACKAGE} {version} (MIT). Do not edit.\n\n"
                "part of 'file_icon.dart';",
                dart_map("_fileNames", file_names, "Whole file names, lowercase; some include a parent folder."),
                dart_map("_extensions", extensions, "Extensions without the leading dot, lowercase; `d.ts` beats `ts`."),
                dart_map("_folders", folders, "Folder names, lowercase, without a leading `.`, `_`, `-` or `__…__`. Open: `<icon>-open`."),
                "/// Icons with a `<icon>_light` variant for light backgrounds.\n"
                "const _lightIcons = <String>{\n" + "".join(f"  {json.dumps(n)},\n" for n in light) + "};",
            ]
        )
        + "\n"
    )
    print(f"{len(defs)} icons, {len(file_names)} file names, {len(extensions)} extensions, {len(folders)} folders")


if __name__ == "__main__":
    main()
